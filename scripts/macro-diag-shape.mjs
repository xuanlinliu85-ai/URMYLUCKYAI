import { readFileSync } from "node:fs";
const s = JSON.parse(readFileSync("public/macro-snapshot.json", "utf8"));
const f = s.futures;
console.log("futures.trends 键数:", Object.keys(f.trends).length, "→", Object.keys(f.trends).slice(0, 12).join(","));
const tk = Object.keys(f.trends)[0];
console.log("样本 trends[" + tk + "] =", JSON.stringify(f.trends[tk]).slice(0, 300));
console.log("\nfutures.varieties len:", f.varieties.length, "首项:", JSON.stringify(f.varieties[0]));
console.log("\nfutures.chains len:", f.chains.length, "首项:", JSON.stringify(f.chains[0]).slice(0, 600));
console.log("\nfutures.movers:", JSON.stringify(f.movers).slice(0, 400));
console.log("\nfutures.signals len:", Array.isArray(f.signals) ? f.signals.length : typeof f.signals);
if (Array.isArray(f.signals) && f.signals.length) console.log("signals 首项:", JSON.stringify(f.signals[0]).slice(0, 400));
console.log("\nspreads len:", f.spreads.length, "→", f.spreads.map(x => x.id).join(", "));
console.log("\nheatmap keys:", Object.keys(f.heatmap).join(","));
console.log("heatmap 样本:", JSON.stringify(f.heatmap).slice(0, 300));
console.log("\nyieldCurve.series keys:", Object.keys(s.yieldCurve.series).join(","));
console.log("yieldCurve.dates len:", s.yieldCurve.dates.length);
console.log("latestShape:", JSON.stringify(s.yieldCurve.latestShape).slice(0, 300));
console.log("\nmovers.stronger len:", s.movers.stronger.length, "首项:", JSON.stringify(s.movers.stronger[0]));
console.log("divergences 首项:", JSON.stringify(s.divergences[0]).slice(0, 500));
